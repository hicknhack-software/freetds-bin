#!/usr/bin/env bash
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
[[ $(dpkg --print-architecture) == amd64 ]]
[[ ${BUILD_JOBS:-2} =~ ^[1-9][0-9]*$ ]]
apt-get update -qq
apt-get install --no-install-recommends -y \
  autoconf automake build-essential ca-certificates gettext git gperf libssl-dev libtool pkg-config
if [[ -d /source ]]; then
  cp -a --no-preserve=ownership /source /tmp/checkout
else
  git clone --depth 1 --branch "$FREETDS_TAG" https://github.com/FreeTDS/freetds.git /tmp/checkout
fi
cd /tmp/checkout
git config --global --add safe.directory "$PWD"
[[ $(git rev-parse HEAD) == "$(git rev-parse "refs/tags/$FREETDS_TAG^{commit}")" ]]
[[ -z $(git status --porcelain --untracked-files=normal) ]]
commit=$(git rev-parse HEAD)
cp -a /tmp/checkout /tmp/freetds
rm -rf /tmp/freetds/.git
# The documentation Makefile needs this generated file without Git metadata.
git log -1 '--pretty=format:<!-- Autogenerated -->%n<!ENTITY ug.date "Date: %ai">%n<!ENTITY ug.id "Git Id: %H">' \
  HEAD -- doc/userguide.xml > /tmp/freetds/doc/userguide_desc.xml
cd /tmp/freetds
# Provide the exact corresponding source alongside the binary distribution.
source_archive="freetds-${FREETDS_TAG}-source.tar.gz"
tar --transform="s,^\\.,freetds-${FREETDS_TAG}," -czf "/output/$source_archive" .
if [[ ! -f configure ]]; then
  NOCONFIGURE=1 ./autogen.sh
fi
./configure --prefix=/usr/local --with-tdsver=7.3 --with-openssl=/usr --disable-readline
make -j"${BUILD_JOBS:-2}"
actual_tag=$(./src/apps/tsql -C | awk '/Version:/ {print $NF}')
[[ $actual_tag == "$FREETDS_TAG" ]] || {
  echo "Expected $FREETDS_TAG but the source reports $actual_tag" >&2
  exit 1
}
make DESTDIR=/tmp/package install
package=/tmp/package/usr/local
mkdir -p "$package/share/doc/freetds-bin"
cp COPYING.txt COPYING_LIB.txt AUTHORS.md "$package/share/doc/freetds-bin/"
cat > "$package/share/doc/freetds-bin/build-info.txt" <<EOF
Upstream: https://github.com/FreeTDS/freetds
Tag: $FREETDS_TAG
Tag commit: $commit
Release source: upstream Git tag
Source: $source_archive
Platform: Debian trixie, linux/amd64
Configure: --prefix=/usr/local --with-tdsver=7.3 --with-openssl=/usr --disable-readline
Bootstrap: NOCONFIGURE=1 ./autogen.sh
Build: make -j${BUILD_JOBS:-2} && make DESTDIR=/tmp/package install
EOF
archive="freetds-${FREETDS_TAG}-debian-trixie-amd64.tar.gz"
tar -C "$package" -czf "/output/$archive" .
cd /output
sha256sum "$archive" > "$archive.sha256"
sha256sum "$source_archive" > "$source_archive.sha256"
echo "Built /output/$archive"
